"""섹터 ETF 레이더 — 앱 진입점.

M2(배선) 단계의 화면이다. **데이터도 스코어링도 아직 없다.**
이 파일이 하는 일은 셋뿐이다 — 화면이 뜬다 · 고지가 보인다 · 출처가 보인다.

🔒 **숫자를 하나도 그리지 않는다.** 지표 카드·랭킹 표·차트·예시 값 전부 없다.
   목업 숫자는 "데이터가 없음"보다 나쁘다 — 팀원 7명은 개발자가 아니라 화면의 87 이
   리허설용인지 실값인지 구별할 수단이 없고, 한 번 본 숫자는 이후 기준점이 된다.
   (→ ADR-SC-0007 "값을 지어내지 않는다")

🔒 **이 파일은 저장소 루트에 있어야 한다. 하위 폴더로 옮기지 마라.**
   Streamlit Cloud 는 의존성 파일을 ① 엔트리포인트가 있는 디렉터리 → ② 저장소 루트
   순으로 찾고 **처음 만난 것 하나만** 쓴다. 이 파일이 루트에 있으면 두 후보가 한 곳으로
   붕괴해 루트 `requirements.txt` 가 확실히 선택된다. 하위 폴더로 옮기는 순간 그 폴더의
   의존성 파일이 루트를 가리고, `sys.path` 도 달라져 앞으로 `import sector` 가 깨진다.
   (→ ADR-SC-0008 ② · `requirements.txt` 머리주석)

🔒 `dashboard/theme.py`(M8) · `pages/`(M9) 를 미리 만들지 않는다.
   들어올 자리를 억지로 비워 두면 빈 껍데기가 규약이 된다.
"""

import streamlit as st

# ── 법적 의무 문구 ───────────────────────────────────────────────────────────
# 🔒 저장소 문서의 문자열을 **글자 그대로** 옮긴 것이다. 바꾸지 않는다.
#    · 출처 = `NOTICE.md` 2장 · `README.md` 8장 · `AGENTS.md` 제약 12
#      KRX Open API 이용약관이 정한 출처 표시 의무다 (→ ADR-SC-0006).
#      "KRX 통계정보" · "출처: 한국거래소" 는 문서와 어긋난다.
#    · 면책 = `NOTICE.md` 3장 · `README.md` · `AGENTS.md` 6장 (세 문서가 일치한다)
#
# ★ `DATA_SOURCE` 를 독립 상수로 둔 이유 — 이것만이 **의무 문자열**이다.
#   "KRX Open API" 는 취득 경로의 이름이라(`AGENTS.md` 경로표) 의무가 아니다. 둘을
#   한 문자열에 섞으면 M8 에서 하단 고정 푸터를 만들 때 무엇이 의무이고 무엇이
#   장식인지 구별할 수 없다. M8·M9 에서 페이지마다 재사용하기도 쉽다.
# 🔒 화면에 **약관 조항 번호를 적지 않는다.** 의무는 이 문자열 표시로 충족되고,
#    번호는 문서(`NOTICE.md`)에만 둔다 — 오기가 생기면 외부 뷰어에게 법적 근거를
#    잘못 주장하게 되고, 개발자가 아닌 팀원이 번호로 얻는 것도 없다.
DATA_SOURCE = "한국거래소 통계정보"
DISCLAIMER = "🔴 **과거 데이터의 요약이다. 투자 권유가 아니다.**"

# ── 화면 본문 ────────────────────────────────────────────────────────────────
# 🔒 마일스톤 코드(M3·M5·M7…)를 화면에 노출하지 않는다. 팀원은 개발자가 아니고
#    (`AGENTS.md` 6장), 첫 화면이 설명해야 할 어휘를 미리 늘릴 이유가 없다.
STATUS_HEADLINE = "아직 데이터가 연결되지 않았다"
STATUS_BODY = """
지금은 **배선 단계**다. 화면이 뜨는 것까지만 만들었다.
그래서 이 화면에는 점수·순위·차트가 **하나도 없다.**

앞으로 들어올 것 — 이것은 **개발 계획이다. 원천에 물어본 결과가 아니다.**

- **섹터 점수·순위** — 하루 1회 로컬 배치가 계산해 Hugging Face(비공개)에 올린 **파생값**
- **일별 시세·ETF 지표** — 한국거래소가 영업일 익일 아침에 전일 데이터를 공개한다
- **준실시간 시세** — KIS 한국투자증권
"""

NOT_DOING_HEADLINE = "이 도구가 하지 않는 것"
NOT_DOING_BODY = """
- **값을 지어내지 않는다.** 못 받은 칸은 `—` 로 남는다.
  0 · 전일값 · 평균으로 채우지 않는다.
- **원자료를 내려주지 않는다.** 공유하는 것은 섹터 집계·점수 같은 **파생값뿐**이다.
"""

TEAM_HEADLINE = "팀원에게"
# ★ 뷰어 초대 금지의 근거를 **정확히** 적는다.
#   🔒 여기에 "KRX 원천 제3자 제공 금지(제11조②)" 를 근거로 달면 안 된다 — 이 앱은
#      설계상 원천을 담지 않고 파생값만 받는다(`README.md` · ADR-SC-0006). 그 조항을
#      끌어오면 *이 앱이 KRX 제한 원천을 들고 있다* 는 아키텍처와 반대되는 사실을
#      팀원에게 심고, 진짜 위험(초대 권한이 전파된다)을 가린다.
TEAM_BODY = """
- 🔒 **뷰어를 다른 사람에게 초대하지 않는다. 초대는 소유자가 한다.**
  초대된 사람은 **또 다른 뷰어를 초대할 수 있고**, 워크스페이스의 분석 정보까지
  함께 열린다 — 기술로 잠기지 않으니 약속으로 막는다.
- 화면이 한동안 안 보이면 잠든 것이다. 열면 다시 깨어난다.
"""

# 푸터 가교 문장 — 데이터가 0건인 화면에 "데이터 출처"가 떠 있는 것은 비개발자에게
# 실제로 모순으로 읽힌다. docstring 에 적어 두면 아무도 읽지 않으므로 **화면에** 둔다.
FOOTER_BRIDGE = (
    "이 화면에는 아직 시세 데이터가 없다. 위 표기는 이 도구가 쓰는 원천을 밝히는 것이지, "
    "지금 화면에 값이 들어와 있다는 뜻이 아니다."
)


def render_header() -> None:
    """제목과 면책을 그린다.

    면책은 **헤더**다. 푸터로 내리면 읽히지 않고, 이 도구의 가장 큰 위험은
    오독이다 (→ `AGENTS.md` 6장 "팀원은 개발자가 아니라 사용자다").
    """
    st.title("섹터 ETF 레이더")
    st.warning(DISCLAIMER)


def render_status() -> None:
    """지금 무엇이 없고 무엇이 올 것인지를 사실로 적는다.

    "화면이 용어를 설명해야 한다"는 규약의 M2 판 이행이다 — 설명할 지표가 아직
    없으므로 이 화면의 상태를 설명한다.

    🔒 "연결됨/끊김" 배지를 두지 않는다. 아무 원천도 부르지 않은 상태에서 상태를
       단정하면 그 배지가 곧 지어낸 값이다 (→ ADR-SC-0007).
    """
    st.subheader(STATUS_HEADLINE)
    st.markdown(STATUS_BODY)

    st.subheader(NOT_DOING_HEADLINE)
    st.markdown(NOT_DOING_BODY)

    st.subheader(TEAM_HEADLINE)
    st.markdown(TEAM_BODY)


def render_footer() -> None:
    """출처 푸터 — **모든 화면 하단에 상시** 표시한다.

    KRX Open API 이용약관 제10조③ 의 의무다 (→ ADR-SC-0006 · `NOTICE.md` 2장).
    조항 번호는 주석에만 둔다 — 화면에는 의무 문자열만 내보낸다.

    🔒 아직 부르지 않는 원천(KIS · DART · 네이버)을 여기 나열하지 않는다.
       v2.0 푸터가 그렇게 해서 부르지도 않는 원천을 출처로 적고 있었다
       (`backend/templates/_partials/_footer.html` — 출처를 `KRX(pykrx)` 로 적는다).
    """
    st.divider()
    st.caption(f"데이터 출처 — **{DATA_SOURCE}**")
    st.caption(FOOTER_BRIDGE)


def main() -> None:
    # page_title 은 브라우저 탭에 뜬다 — 팀원은 URL 하나만 받으므로 탭 이름이 유일한
    # 식별자다. 색·폰트·`layout` 은 M8(`theme.py`)에서 정한다. 여기서 정하지 않는다.
    st.set_page_config(page_title="섹터 ETF 레이더", page_icon="📊")

    render_header()
    # ★ `finally` 로 감싼 이유 — 출처 표시는 **의무**이고, 본문에서 예외가 나도
    #   빠지면 안 된다. Streamlit 은 이미 그려진 요소를 지우지 않으므로, 본문이
    #   중간에 죽어도 푸터가 하단에 남고 그 뒤에 traceback 이 붙는다.
    #   M2 는 데이터가 0건이라 지금 예외가 날 일이 없지만, 이 구조를 지금 박아 두지
    #   않으면 M9 이후 "랭킹이 그려진 뒤 차트에서 예외 → 파생값만 남고 출처는 없는
    #   화면" 경로가 그대로 열린다.
    try:
        render_status()
    finally:
        render_footer()


# `if __name__ == "__main__"` 가드를 두지 않는다. Streamlit 은 상호작용마다 이
# 스크립트를 위에서 아래로 다시 실행하므로 가드가 이득 없이 실패 지점만 늘린다.
main()
